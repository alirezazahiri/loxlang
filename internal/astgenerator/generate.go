package astgenerator

import (
	"fmt"
	"go/format"
	"strings"

	"loxlang/pkg/utils"
)

type field struct {
	Type string
	Name string
}

type node struct {
	Name   string
	Fields []field
}

func (a *AstGenerator) Generate() (string, []byte) {
	filename := fmt.Sprintf("%s.go", strings.ToLower(a.baseName))

	nodes := parseNodes(a.types)

	var b strings.Builder

	b.WriteString(a.buildHeader())

	visitorMethods := []string{}

	for _, n := range nodes {

		b.WriteString(renderStruct(n))
		b.WriteString(renderConstructor(n))
		b.WriteString(renderMarker(n.Name, a.baseName))
		b.WriteString(renderAccept(n.Name, a.baseName))

		visitorMethods = append(visitorMethods,
			renderVisitorMethod(n.Name, a.baseName))
	}

	b.WriteString(renderVisitor(a.baseName, visitorMethods))

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}

	return filename, src
}

func parseNodes(types []string) []node {
	nodes := make([]node, 0, len(types))

	for _, t := range types {
		parts := strings.Split(t, ":")

		name := strings.TrimSpace(parts[0])
		rawFields := strings.Split(strings.TrimSpace(parts[1]), ",")

		fields := []field{}

		for _, f := range rawFields {
			p := strings.Fields(strings.TrimSpace(f))

			fields = append(fields, field{
				Type: p[0],
				Name: p[1],
			})
		}

		nodes = append(nodes, node{
			Name:   name,
			Fields: fields,
		})
	}

	return nodes
}

func (a *AstGenerator) buildHeader() string {
	var b strings.Builder

	b.WriteString("// Code generated by astgenerator. DO NOT EDIT.\n\n")
	b.WriteString("package ast\n\n")

	if len(a.imports) > 0 {
		b.WriteString("import (\n")
		for _, i := range a.imports {
			b.WriteString(fmt.Sprintf("\"%s\"\n", i))
		}
		b.WriteString(")\n\n")
	}

	b.WriteString(fmt.Sprintf(
		"type %s interface {\n"+
			"%s()\n"+
			"Accept(visitor %sVisitor) any\n"+
			"}\n\n",
		a.baseName,
		strings.ToLower(a.baseName),
		a.baseName,
	))

	return b.String()
}

func renderStruct(n node) string {
	var fields []string

	for _, f := range n.Fields {
		fields = append(fields,
			fmt.Sprintf("%s %s", utils.CapFirst(f.Name), f.Type))
	}

	return fmt.Sprintf(
		"type %s struct {\n%s\n}\n\n",
		n.Name,
		strings.Join(fields, "\n"),
	)
}

func renderConstructor(n node) string {

	params := []string{}
	inits := []string{}

	for _, f := range n.Fields {

		params = append(params,
			fmt.Sprintf("%s %s", f.Name, f.Type))

		inits = append(inits,
			fmt.Sprintf("%s: %s",
				utils.CapFirst(f.Name), f.Name))
	}

	return fmt.Sprintf(
		"func New%s(%s) *%s {\n"+
			"return &%s{\n%s,\n}\n}\n\n",
		n.Name,
		strings.Join(params, ", "),
		n.Name,
		n.Name,
		strings.Join(inits, ",\n"),
	)
}

func renderMarker(name, base string) string {
	return fmt.Sprintf(
		"func (*%s) %s() {}\n\n",
		name,
		strings.ToLower(base),
	)
}

func renderAccept(name, base string) string {
	return fmt.Sprintf(
		"func (e *%s) Accept(visitor %sVisitor) any {\n"+
			"return visitor.Visit%s%s(e)\n}\n\n",
		name,
		base,
		name,
		base,
	)
}

func renderVisitorMethod(name, base string) string {

	arg := strings.ToLower(base)

	return fmt.Sprintf(
		"Visit%s%s(%s *%s) any",
		name,
		base,
		arg,
		name,
	)
}

func renderVisitor(base string, methods []string) string {

	return fmt.Sprintf(
		"type %sVisitor interface {\n%s\n}\n",
		base,
		strings.Join(methods, "\n"),
	)
}
